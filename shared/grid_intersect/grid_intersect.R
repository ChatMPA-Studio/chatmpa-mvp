# grid_intersect.R
#
# Utility functions to query the attributed coastal prosperity grid.
# Called by skills that need socioeconomic or administrative variables
# (INEGI, municipal data, CONAPESCA via georeferenced ports).
#
# TWO-TRACK ARCHITECTURE — which track to use:
#
#   Track A: Environmental satellite data (SST, Chl, NPP)
#     → Extract directly from the MPA polygon using get_amp_geometry() or
#       get_lme_geometry() from shared/spatial_join/spatial_join.R.
#       Works for ALL MPAs, including offshore (Revillagigedo, Guadalupe).
#       Does NOT use this file.
#
#   Track B: Socioeconomic / administrative / CONAPESCA data
#     → Use this file to retrieve coastal grid cells.
#       Coastal MPAs only — offshore MPAs have zero grid cells (returns
#       empty sf with a warning, not an error).
#
# Grid file: data/prosperity_grid_attributed.gpkg
#   Generated by: shared/grid_prep/setup_grid_attributes.R
#   Key columns added by setup:
#     mpa_id     — ANP_ID (integer); NA if cell not inside any MPA
#     nombre_amp — ANP name (character); NA if cell not inside any MPA
#   All original prosperity variables are retained.

suppressPackageStartupMessages(library(sf))

# ── .load_grid ─────────────────────────────────────────────────────────────────
# Cached grid load (loaded once per R session).

.grid_cache <- new.env(parent = emptyenv())

.load_grid <- function(grid_path = "data/prosperity_grid_attributed.gpkg") {
  if (!exists("grid", envir = .grid_cache)) {
    if (!file.exists(grid_path))
      stop("Attributed grid not found at '", grid_path, "'. ",
           "Run shared/grid_prep/setup_grid_attributes.R first.")
    .grid_cache$grid <- sf::st_read(grid_path, quiet = TRUE)
  }
  .grid_cache$grid
}

# ── get_grid_cells_by_amp ──────────────────────────────────────────────────────
#
# Returns all coastal grid cells assigned to a specific MPA by name.
# Empty sf (with warning) for offshore MPAs that have no coastal cells.
#
# Args:
#   amp_name   character — MPA name matching the `nombre_amp` column.
#              Case-insensitive partial matching supported via `exact` arg.
#   exact      logical — if TRUE (default), require exact match;
#              if FALSE, use case-insensitive grep.
#   grid_path  character — path to the attributed grid gpkg.
#
# Returns: sf object (subset of the grid) with all columns retained.

get_grid_cells_by_amp <- function(amp_name, exact = TRUE,
                                  grid_path = "data/prosperity_grid_attributed.gpkg") {
  grid <- .load_grid(grid_path)

  if (exact) {
    cells <- grid[!is.na(grid$nombre_amp) & grid$nombre_amp == amp_name, ]
  } else {
    idx   <- grep(amp_name, grid$nombre_amp, ignore.case = TRUE)
    cells <- grid[idx, ]
  }

  if (nrow(cells) == 0) {
    warning("No coastal grid cells found for MPA '", amp_name, "'. ",
            "This MPA may be entirely offshore (e.g. Revillagigedo, Guadalupe). ",
            "Use Track A (MPA polygon extraction) for environmental data. ",
            "Socioeconomic grid variables are not available for this MPA.")
  } else {
    message("  get_grid_cells_by_amp('", amp_name, "'): ", nrow(cells), " cells returned.")
  }

  cells
}

# ── get_grid_cells_by_roi ─────────────────────────────────────────────────────
#
# Returns all coastal grid cells that intersect a user-defined polygon (ROI).
# Used when the demo user draws a custom area on the map.
#
# Args:
#   roi_polygon  sf object — a single polygon (or multipolygon) in any CRS;
#                will be reprojected to match the grid if needed.
#   grid_path    character — path to the attributed grid gpkg.
#
# Returns: sf object (subset of the grid) with all columns retained.

get_grid_cells_by_roi <- function(roi_polygon,
                                  grid_path = "data/prosperity_grid_attributed.gpkg") {
  grid <- .load_grid(grid_path)

  if (!inherits(roi_polygon, "sf") && !inherits(roi_polygon, "sfc"))
    stop("roi_polygon must be an sf or sfc object.")

  # Reproject ROI to grid CRS if needed
  if (!identical(sf::st_crs(roi_polygon), sf::st_crs(grid)))
    roi_polygon <- sf::st_transform(roi_polygon, sf::st_crs(grid))

  cells <- sf::st_filter(grid, roi_polygon, .predicate = sf::st_intersects)

  if (nrow(cells) == 0) {
    warning("No coastal grid cells found within the provided ROI. ",
            "The ROI may be entirely offshore or outside the grid coverage area. ",
            "Use Track A (MPA polygon extraction) for environmental data.")
  } else {
    message("  get_grid_cells_by_roi(): ", nrow(cells), " cells returned.")
    n_mpa <- sum(!is.na(cells$nombre_amp))
    if (n_mpa > 0)
      message("  ", n_mpa, " cells inside an MPA (", length(unique(cells$nombre_amp[!is.na(cells$nombre_amp)])),
              " unique MPAs); ", nrow(cells) - n_mpa, " cells outside any MPA.")
  }

  cells
}

# ── get_grid_cells_by_region ──────────────────────────────────────────────────
#
# Returns all coastal grid cells assigned to a fishing management region.
# Requires the grid to have a `region_id` column, which is added by
# setup_grid_attributes.R after conapesca-lfo-regions is run.
# BLOCKED until georeferenced landing ports and conapesca-lfo-regions are ready.
#
# Args:
#   region_id  integer or character — region identifier.
#   grid_path  character — path to the attributed grid gpkg.

get_grid_cells_by_region <- function(region_id,
                                     grid_path = "data/prosperity_grid_attributed.gpkg") {
  grid <- .load_grid(grid_path)

  if (!"region_id" %in% names(grid))
    stop("Column 'region_id' not found in grid. ",
         "Run conapesca-lfo-regions skill first, then re-run ",
         "setup_grid_attributes.R to stamp region IDs onto the grid. ",
         "This function is BLOCKED until georeferenced landing ports are available.")

  cells <- grid[!is.na(grid$region_id) & grid$region_id == region_id, ]

  if (nrow(cells) == 0)
    warning("No grid cells found for region_id '", region_id, "'.")
  else
    message("  get_grid_cells_by_region(", region_id, "): ", nrow(cells), " cells returned.")

  cells
}
